package com.aswin.financetracker.integration;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.aswin.financetracker.FinanceTrackerApplication;
import com.aswin.financetracker.repository.BudgetRepository;
import com.aswin.financetracker.repository.ExpenseRepository;
import com.aswin.financetracker.repository.IncomeRepository;
import com.aswin.financetracker.repository.SubscriptionRepository;
import com.aswin.financetracker.repository.UserRepository;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.HashSet;
import java.util.Set;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.context.ConfigurableApplicationContext;

class LegacyProductionDatabaseMigrationIntegrationTest {

    private static boolean isDockerAvailable() {
        try {
            Process process = new ProcessBuilder("docker", "info").redirectErrorStream(true).start();
            return process.waitFor() == 0;
        } catch (Exception e) {
            return false;
        }
    }

    @Test
    @DisplayName("Reproduce legacy production database, run Flyway baseline-on-migrate with baseline-version=0, assert data migration, and boot with ddl-auto=validate")
    void testLegacyProductionDatabaseMigrationAndContextBoot() throws Exception {
        if (isDockerAvailable()) {
            try (org.testcontainers.containers.PostgreSQLContainer<?> postgres =
                     new org.testcontainers.containers.PostgreSQLContainer<>("postgres:16-alpine")) {
                postgres.start();
                String dbUrl = postgres.getJdbcUrl();
                String dbUser = postgres.getUsername();
                String dbPassword = postgres.getPassword();
                System.out.println("[DATABASE REPORT] Docker is available. Migration test executed using real PostgreSQL via Testcontainers: " + dbUrl);
                executeMigrationAndValidateContext(dbUrl, dbUser, dbPassword, false);
            }
        } else {
            String dbUrl = "jdbc:h2:mem:legacy_prod_sim_db;DB_CLOSE_DELAY=-1;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE";
            String dbUser = "sa";
            String dbPassword = "";
            System.out.println("[DATABASE REPORT] Docker is not available on this environment. Migration test executed using H2 in PostgreSQL compatibility mode: " + dbUrl);
            executeMigrationAndValidateContext(dbUrl, dbUser, dbPassword, true);
        }
    }

    private void executeMigrationAndValidateContext(String dbUrl, String dbUser, String dbPassword, boolean isH2) throws Exception {
        // 1. Create the legacy schema as Hibernate ddl-auto=update created from ORIGINAL entities:
        //    users(id, username, email, created_at) and incomes, expenses, budgets, subscriptions WITHOUT user_id.
        //    Also include duplicate (user_id, category) budget rows and username-only user.
        try (Connection conn = DriverManager.getConnection(dbUrl, dbUser, dbPassword);
             Statement stmt = conn.createStatement()) {

            if (isH2) {
                stmt.execute("DROP ALL OBJECTS");
            } else {
                stmt.execute("DROP SCHEMA public CASCADE; CREATE SCHEMA public;");
            }

            stmt.execute("""
                CREATE TABLE users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(100) NOT NULL UNIQUE,
                    email VARCHAR(150),
                    created_at TIMESTAMP NOT NULL
                );
                
                CREATE TABLE incomes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    amount NUMERIC(14, 2) NOT NULL,
                    source VARCHAR(50) NOT NULL,
                    date DATE NOT NULL,
                    note VARCHAR(500)
                );
                
                CREATE TABLE expenses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    amount NUMERIC(14, 2) NOT NULL,
                    category VARCHAR(50) NOT NULL,
                    date DATE NOT NULL,
                    description VARCHAR(500) NOT NULL
                );
                
                CREATE TABLE budgets (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    category VARCHAR(50) NOT NULL,
                    monthly_limit NUMERIC(14, 2) NOT NULL
                );
                
                CREATE TABLE subscriptions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(150) NOT NULL,
                    amount NUMERIC(14, 2) NOT NULL,
                    billing_cycle VARCHAR(50) NOT NULL,
                    next_due_date DATE NOT NULL,
                    category VARCHAR(50) NOT NULL,
                    active BOOLEAN NOT NULL DEFAULT TRUE
                );
            """);

            // Seed legacy user with email and legacy user with username only
            stmt.execute("INSERT INTO users (username, email, created_at) VALUES ('legacy_default_user', 'legacy@example.com', CURRENT_TIMESTAMP)");
            stmt.execute("INSERT INTO users (username, email, created_at) VALUES ('legacy_username_only', NULL, CURRENT_TIMESTAMP)");

            stmt.execute("INSERT INTO incomes (amount, source, date, note) VALUES (3500.00, 'SALARY', '2026-08-01', 'August Salary')");
            stmt.execute("INSERT INTO incomes (amount, source, date, note) VALUES (500.00, 'FREELANCE', '2026-08-15', 'Freelance Gig')");

            stmt.execute("INSERT INTO expenses (amount, category, date, description) VALUES (120.50, 'FOOD', '2026-08-05', 'Groceries')");
            stmt.execute("INSERT INTO expenses (amount, category, date, description) VALUES (45.00, 'TRAVEL', '2026-08-10', 'Train Ticket')");

            // Seed duplicate budgets to test migration deduplication
            stmt.execute("INSERT INTO budgets (category, monthly_limit) VALUES ('FOOD', 600.00)");
            stmt.execute("INSERT INTO budgets (category, monthly_limit) VALUES ('FOOD', 650.00)");
            stmt.execute("INSERT INTO budgets (category, monthly_limit) VALUES ('TRAVEL', 200.00)");

            stmt.execute("INSERT INTO subscriptions (name, amount, billing_cycle, next_due_date, category, active) VALUES ('Netflix', 15.99, 'MONTHLY', '2026-09-01', 'ENTERTAINMENT', true)");
            stmt.execute("INSERT INTO subscriptions (name, amount, billing_cycle, next_due_date, category, active) VALUES ('Gym', 50.00, 'MONTHLY', '2026-09-05', 'HEALTH', true)");
        }

        // 2. Run Flyway with baseline-on-migrate=true and baseline-version=0
        Flyway flyway = Flyway.configure()
            .dataSource(dbUrl, dbUser, dbPassword)
            .baselineOnMigrate(true)
            .baselineVersion("0")
            .load();

        flyway.migrate();

        // 3. Assert: users has full_name, email, password_hash, role, enabled;
        //    username-only legacy row has valid non-null full_name and unique email;
        //    every old row in expenses/incomes/budgets/subscriptions has a non-null user_id pointing to legacy user;
        //    the legacy users have enabled=false;
        //    duplicate budget rows were deduplicated.
        try (Connection conn = DriverManager.getConnection(dbUrl, dbUser, dbPassword);
             Statement stmt = conn.createStatement()) {

            Set<String> columnNames = new HashSet<>();
            try (ResultSet rs = stmt.executeQuery("SELECT * FROM users WHERE 1=0")) {
                java.sql.ResultSetMetaData rsMeta = rs.getMetaData();
                for (int i = 1; i <= rsMeta.getColumnCount(); i++) {
                    columnNames.add(rsMeta.getColumnName(i).toLowerCase());
                }
            }
            assertTrue(columnNames.contains("full_name"), "users table must contain full_name column");
            assertTrue(columnNames.contains("email"), "users table must contain email column");
            assertTrue(columnNames.contains("password_hash"), "users table must contain password_hash column");
            assertTrue(columnNames.contains("role"), "users table must contain role column");
            assertTrue(columnNames.contains("enabled"), "users table must contain enabled column");

            // Retrieve primary legacy user
            Long legacyUserId = null;
            try (ResultSet rs = stmt.executeQuery("SELECT id, username, email, full_name, password_hash, role, enabled FROM users WHERE username = 'legacy_default_user'")) {
                assertTrue(rs.next(), "Legacy default user must exist");
                legacyUserId = rs.getLong("id");
                assertNotNull(legacyUserId);
                assertEquals("legacy@example.com", rs.getString("email"));
                assertEquals("legacy_default_user", rs.getString("full_name"));
                assertNotNull(rs.getString("password_hash"));
                assertEquals("USER", rs.getString("role"));
                assertFalse(rs.getBoolean("enabled"), "Legacy user must have enabled=false");
            }

            // Assert username-only user received email and full_name
            try (ResultSet rs = stmt.executeQuery("SELECT id, username, email, full_name, enabled FROM users WHERE username = 'legacy_username_only'")) {
                assertTrue(rs.next(), "Legacy username-only user must exist");
                assertEquals("legacy_username_only@legacy.local", rs.getString("email"));
                assertEquals("legacy_username_only", rs.getString("full_name"));
                assertFalse(rs.getBoolean("enabled"), "Legacy user must have enabled=false");
            }

            // Assert user_id on all child records points to primary legacy user
            try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) AS cnt FROM incomes WHERE user_id IS NULL OR user_id != " + legacyUserId)) {
                assertTrue(rs.next());
                assertEquals(0, rs.getInt("cnt"), "All legacy income rows must point to legacy user");
            }

            try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) AS cnt FROM expenses WHERE user_id IS NULL OR user_id != " + legacyUserId)) {
                assertTrue(rs.next());
                assertEquals(0, rs.getInt("cnt"), "All legacy expense rows must point to legacy user");
            }

            try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) AS cnt FROM budgets WHERE user_id IS NULL OR user_id != " + legacyUserId)) {
                assertTrue(rs.next());
                assertEquals(0, rs.getInt("cnt"), "All legacy budget rows must point to legacy user");
            }

            // Assert budgets deduplication: duplicate FOOD budget was removed, 2 distinct categories remain
            try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) AS cnt FROM budgets")) {
                assertTrue(rs.next());
                assertEquals(2, rs.getInt("cnt"), "Duplicate budget must be deduplicated (FOOD and TRAVEL remaining)");
            }

            try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) AS cnt FROM subscriptions WHERE user_id IS NULL OR user_id != " + legacyUserId)) {
                assertTrue(rs.next());
                assertEquals(0, rs.getInt("cnt"), "All legacy subscription rows must point to legacy user");
            }
        }

        // 4. Start the Spring context with ddl-auto=validate against that migrated schema and assert it boots cleanly.
        try (ConfigurableApplicationContext context = new SpringApplicationBuilder(FinanceTrackerApplication.class)
                .run(
                    "--spring.profiles.active=test",
                    "--spring.datasource.url=" + dbUrl,
                    "--spring.datasource.username=" + dbUser,
                    "--spring.datasource.password=" + dbPassword,
                    "--spring.jpa.hibernate.ddl-auto=validate",
                    "--spring.flyway.enabled=false",
                    "--spring.main.banner-mode=off",
                    "--server.port=0"
                )) {

            assertTrue(context.isActive(), "Spring application context must successfully boot with ddl-auto=validate");

            UserRepository userRepository = context.getBean(UserRepository.class);
            ExpenseRepository expenseRepository = context.getBean(ExpenseRepository.class);
            IncomeRepository incomeRepository = context.getBean(IncomeRepository.class);
            BudgetRepository budgetRepository = context.getBean(BudgetRepository.class);
            SubscriptionRepository subscriptionRepository = context.getBean(SubscriptionRepository.class);

            assertTrue(userRepository.count() >= 2, "User repository must find the migrated users");
            assertEquals(2, expenseRepository.count(), "Expense repository must access the 2 migrated expenses");
            assertEquals(2, incomeRepository.count(), "Income repository must access the 2 migrated incomes");
            assertEquals(2, budgetRepository.count(), "Budget repository must access the 2 deduplicated budgets");
            assertEquals(2, subscriptionRepository.count(), "Subscription repository must access the 2 migrated subscriptions");
        }
    }
}
